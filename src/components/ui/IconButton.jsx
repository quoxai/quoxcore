/**
 * IconButton Component
 *
 * @param {string} icon - Icon name from ICONS map
 * @param {string} label - Accessible label (required for a11y)
 * @param {function} onClick - Click handler
 * @param {string} className - Additional CSS classes
 * @param {string} size - Button size: 'sm' (24px), 'md' (32px), 'lg' (40px)
 * @param {string} variant - Visual variant: 'ghost', 'outline', 'solid'
 * @param {boolean} disabled - Disabled state
 * @param {string} title - Tooltip text
 */
export function IconButton({
  icon,
  label,
  onClick,
  className = '',
  size = 'md',
  variant = 'ghost',
  disabled = false,
  title,
  ...props
}) {
  const iconElement = ICONS[icon];

  if (!iconElement) {
    console.warn(`IconButton: Unknown icon "${icon}". Available: ${Object.keys(ICONS).join(', ')}`);
  }

  return (
    <button
      type="button"
      className={`icon-button icon-button--${size} icon-button--${variant} ${className}`}
      onClick={onClick}
      disabled={disabled}
      aria-label={label}
      title={title || label}
      {...props}
    >
      {iconElement || (
        // Fallback: render a visible placeholder so we know it's broken
        <span style={{
          width: 16,
          height: 16,
          background: 'red',
          display: 'block',
          borderRadius: 2
        }} />
      )}
    </button>
  );
}

/**
 * Get an icon element directly (for use outside IconButton)
 */
export function getIcon(name) {
  return ICONS[name] || null;
}

/**
 * Check if an icon exists
 */
export function hasIcon(name) {
  return name in ICONS;
}

export default IconButton;
