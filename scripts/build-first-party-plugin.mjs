#!/usr/bin/env node
/**
 * Build + sign + publish a first-party Quox plugin (LICENSE-LAUNCH LL-7).
 *
 *   node scripts/build-first-party-plugin.mjs quoxbox-macmini
 *
 * Steps:
 *   1. vite build (vite.plugin.config.mjs, root = plugins-src/<id>) — emits
 *      dist/plugin.esm.js + dist/plugin.css and, when adm-zip is reachable
 *      from the SDK, a <id>.quoxplugin ZIP. We build the ZIP ourselves if not.
 *   2. Sign the ZIP with scripts/sign-plugin.js (Ed25519 over the canonical
 *      manifest) using the Quox publisher key.
 *   3. Unpack manifest.json / plugin.esm.js / plugin.css / signature.json into
 *      services/auth/first-party-plugins/<id>/, which is what the auth service
 *      provisions from.
 *
 * The private key NEVER lives in this repo. It defaults to
 * ~/.config/quox/plugin-signing/quox-signing.key (0600, generated by
 * scripts/generate-signing-key.js) and can be overridden with --key. Its
 * PUBLIC half must be listed in src/config/officialSigningKeys.js or the
 * dashboard will refuse the root-route privilege at activation.
 */

import { spawnSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import fs from 'node:fs';
import os from 'node:os';
import AdmZip from 'adm-zip';

const REPO = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');

const args = process.argv.slice(2);
const pluginId = args.find((a) => !a.startsWith('--'));
if (!pluginId) {
    console.error('Usage: node scripts/build-first-party-plugin.mjs <pluginId> [--key <private-key>]');
    process.exit(1);
}
const keyIdx = args.indexOf('--key');
const keyPath = keyIdx !== -1 && args[keyIdx + 1]
    ? path.resolve(args[keyIdx + 1])
    : path.join(os.homedir(), '.config', 'quox', 'plugin-signing', 'quox-signing.key');

const projectRoot = path.join(REPO, 'plugins-src', pluginId);
const distDir = path.join(projectRoot, 'dist');
const zipPath = path.join(projectRoot, `${pluginId}.quoxplugin`);
const outDir = path.join(REPO, 'services', 'auth', 'first-party-plugins', pluginId);

function run(cmd, cmdArgs, opts = {}) {
    const r = spawnSync(cmd, cmdArgs, { stdio: 'inherit', ...opts });
    if (r.status !== 0) {
        console.error(`\n[build-first-party-plugin] "${cmd} ${cmdArgs.join(' ')}" failed (exit ${r.status})`);
        process.exit(r.status || 1);
    }
}

// ── 1. Build ──────────────────────────────────────────────────────────────
console.log(`Ⓠ QUOX │ building first-party plugin ${pluginId}`);
run('npx', ['vite', 'build', '--config', path.join(REPO, 'vite.plugin.config.mjs')], {
    cwd: projectRoot,
    env: { ...process.env, QUOX_PLUGIN_ID: pluginId },
});

const bundlePath = path.join(distDir, 'plugin.esm.js');
if (!fs.existsSync(bundlePath)) {
    console.error(`[build-first-party-plugin] no ${bundlePath} after build`);
    process.exit(1);
}

// ── 2. Package (the SDK's closeBundle does this when adm-zip is reachable
//        from ITS node_modules; ours is authoritative either way) ──────────
const zip = new AdmZip();
zip.addLocalFile(path.join(projectRoot, 'manifest.json'));
zip.addLocalFile(bundlePath);
const cssPath = path.join(distDir, 'plugin.css');
const hasCss = fs.existsSync(cssPath);
if (hasCss) zip.addLocalFile(cssPath);
const assetsDir = path.join(distDir, 'assets');
if (fs.existsSync(assetsDir)) zip.addLocalFolder(assetsDir, 'assets');
zip.writeZip(zipPath);
console.log(`  packaged ${path.relative(REPO, zipPath)}`);

// ── 3. Sign ───────────────────────────────────────────────────────────────
if (!fs.existsSync(keyPath)) {
    console.error(
        `\n[build-first-party-plugin] signing key not found: ${keyPath}\n`
        + '  Generate one with: node scripts/generate-signing-key.js --out ~/.config/quox/plugin-signing\n'
        + '  then add its printed base64 public key to src/config/officialSigningKeys.js.',
    );
    process.exit(1);
}
run('node', [path.join(REPO, 'scripts', 'sign-plugin.js'), '--plugin', zipPath, '--key', keyPath]);

// ── 4. Publish to the auth service's first-party bundle directory ─────────
const signed = new AdmZip(zipPath);
const signature = signed.getEntry('signature.json');
if (!signature) {
    console.error('[build-first-party-plugin] signing produced no signature.json');
    process.exit(1);
}
fs.mkdirSync(outDir, { recursive: true });
// F2: publish the manifest from the SIGNED zip (it carries integrity), never the source one.
fs.writeFileSync(path.join(outDir, 'manifest.json'), signed.getEntry('manifest.json').getData());
fs.copyFileSync(bundlePath, path.join(outDir, 'plugin.esm.js'));
if (hasCss) fs.copyFileSync(cssPath, path.join(outDir, 'plugin.css'));
fs.writeFileSync(path.join(outDir, 'signature.json'), signature.getData());

const kb = (p) => `${(fs.statSync(p).size / 1024).toFixed(1)} KB`;
console.log(`\nⓆ QUOX │ ${pluginId} published to ${path.relative(REPO, outDir)}/`);
console.log(`  plugin.esm.js  ${kb(path.join(outDir, 'plugin.esm.js'))}`);
if (hasCss) console.log(`  plugin.css     ${kb(path.join(outDir, 'plugin.css'))}`);
console.log(`  signature.json ${kb(path.join(outDir, 'signature.json'))}`);
