function buildCuratedEntry(tpl) {
  return {
    v: '1.0',
    type: 'workflow',
    id: tpl.id,
    source: 'quox-curated',
    identity: {
      name: tpl.name,
      shortName: tpl.shortName,
      description: tpl.description,
      useCases: [],
      category: tpl.category,
      tags: tpl.tags,
      icon: getCategoryIcon(tpl.category),
      color: getCategoryColor(tpl.category)
    },
    capabilities: {
      integrations: tpl.integrations,
      nodeTypes: tpl.nodeTypes
    },
    trigger: {
      type: tpl.triggerType
    },
    safety: {
      defconLevel: 'BLUE',
      requiresApproval: false
    },
    execution: {
      engine: 'quoxflow'
    },
    workflowFile: `Quox_Curated/${tpl.slug}.json`,
    nodeCount: tpl.nodeCount,
    edgeCount: tpl.edgeCount
  }
}

function getCategoryIcon(category) {
  const icons = {
    monitoring: 'activity', automation: 'zap', integration: 'link',
    notification: 'bell', 'data-processing': 'database', 'ai-llm': 'brain',
    security: 'shield', devops: 'git-branch', communication: 'message-circle',
    productivity: 'folder', other: 'box'
  }
  return icons[category] || 'box'
}

function getCategoryColor(category) {
  const colors = {
    monitoring: '#10b981', automation: '#f59e0b', integration: '#6366f1',
    notification: '#ef4444', 'data-processing': '#8b5cf6', 'ai-llm': '#ec4899',
    security: '#3b82f6', devops: '#14b8a6', communication: '#06b6d4',
    productivity: '#84cc16', other: '#6b7280'
  }
  return colors[category] || '#6b7280'
}

// Main
const raw = fs.readFileSync(INDEX_PATH, 'utf8')
const index = JSON.parse(raw)

console.log(`Loaded index: ${index.workflows.length} entries`)

// Tag all existing entries with source: 'n8n-imported' (unless they already have a source)
let tagged = 0
for (const w of index.workflows) {
  if (!w.source) {
    w.source = 'n8n-imported'
    tagged++
  }
}
console.log(`Tagged ${tagged} entries as n8n-imported`)

// Build curated entries
const curatedEntries = CURATED_TEMPLATES.map(buildCuratedEntry)

// Verify all curated JSON files exist
for (const tpl of CURATED_TEMPLATES) {
  const jsonPath = path.join(CURATED_DIR, `${tpl.slug}.json`)
  if (!fs.existsSync(jsonPath)) {
    console.error(`MISSING: ${jsonPath}`)
    process.exit(1)
  }
  // Parse to confirm valid JSON
  JSON.parse(fs.readFileSync(jsonPath, 'utf8'))
}
console.log(`All 12 curated template JSON files verified`)

// Append curated entries
index.workflows.push(...curatedEntries)

// Update header metadata
index.totalWorkflows = index.workflows.length
index.generatedAt = new Date().toISOString()

// Rebuild categories count
const catCounts = {}
for (const w of index.workflows) {
  const cat = w.identity?.category || 'other'
  catCounts[cat] = (catCounts[cat] || 0) + 1
}
index.categories = catCounts

// Write back
const output = JSON.stringify(index, null, 2)
fs.writeFileSync(INDEX_PATH, output, 'utf8')

console.log(`Written: ${INDEX_PATH}`)
console.log(`Total workflows: ${index.workflows.length}`)
console.log(`Curated entries: ${curatedEntries.length}`)
console.log(`n8n-imported entries: ${index.workflows.filter(w => w.source === 'n8n-imported').length}`)
console.log('Done.')
