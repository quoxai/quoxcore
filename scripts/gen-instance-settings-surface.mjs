#!/usr/bin/env node
// SETEC S2: regenerate src/config/instanceSettingsSurface.json from the env
// registry. The Instance settings page renders every instance|infra entry, so
// the guardrail can verify "instance settings" surface claims against this list.
import { createRequire } from 'node:module';
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const require = createRequire(import.meta.url);
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const { ENV_REGISTRY } = require(path.join(root, 'services/shared/envRegistry.cjs'));
const { surfaceEntries } = require(path.join(root, 'services/shared/envProjection.cjs'));

const names = [...new Set(surfaceEntries(ENV_REGISTRY).map((e) => e.name))].sort();
const out = {
    _comment: 'Generated by scripts/gen-instance-settings-surface.mjs from services/shared/envRegistry.cjs (instance|infra entries). Do not hand-edit.',
    names,
};
writeFileSync(path.join(root, 'src/config/instanceSettingsSurface.json'), JSON.stringify(out, null, 2) + '\n');
console.log(`instanceSettingsSurface.json: ${names.length} names`);
