// WHY THIS EXISTS (VAULT-INTEG P13, 2026-09-06):
//   ~105 env-only, user-facing settings existed with no dashboard/Settings
//   surface, and three feature flags in the UI LIED about their own state
//   because the code path that read them bypassed the settings store and read
//   process.env directly instead. There was no single place naming every
//   environment variable a service could read, so nobody could audit which
//   ones needed a Settings surface. This registry is the ratchet: it does NOT
//   remediate the existing backlog (VAULT-INTEG P14), it stops a NEW
//   unregistered process.env read from shipping (see
//   src/test/envRegistryCompleteness.test.js and
//   scripts/pre-commit-env-check.sh).
//
