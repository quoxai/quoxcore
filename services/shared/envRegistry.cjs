//   Every entry seeded as 'legacy-unclassified' has been read in context
//   (grep usage under services/**) and assigned a real classification.
//   ZERO 'legacy-unclassified' entries remain — the completeness test now
//   asserts that stays true (src/test/envRegistryCompleteness.test.js).
//   Counts by classification as of this pass:
//     infra: 66
//     instance: 144
//     secret: 87
//     user: 81
//   Of the 'user' entries, a large share (the *_ENABLED/*_ORGS/*_MODE style
//   flags already exposed by services/collector/lib/platformCapabilities.js)
//   have a real surface today ("platform settings registry"). The rest name
//   the settings area that SHOULD own them but doesn't yet — that gap is the
//   P14 build-out, not a defect in this pass.
//
// Entry shape:
//   name           - the env var name, exactly as read (process.env.<NAME>)
//   services       - array of services/<dir> names that read it
